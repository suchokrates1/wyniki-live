# How a date reads in the mail of each language.
DATE_FORMATS = {"pl": "{d}.{m}.{y}", "de": "{d}.{m}.{y}", "en": "{d}/{m}/{y}", "it": "{d}/{m}/{y}",
                "es": "{d}/{m}/{y}", "fr": "{d}/{m}/{y}", "lt": "{y}-{m}-{d}"}


def texts(language: str) -> dict[str, str]:
    return TEXTS.get(language) or TEXTS["en"]


def format_date(iso: str, language: str) -> str:
    year, month, day = iso.split("-")
    return DATE_FORMATS.get(language, DATE_FORMATS["en"]).format(d=day, m=month, y=year)
